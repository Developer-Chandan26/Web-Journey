// && Logical AND Operator
let marks = 78;

if (marks >= 33 && marks >= 80) {
  console.log("Pass");
  console.log("A+");
}

// || Logical OR Operator
let score = 75;

if (score >= 33 || score >= 80) {
  console.log("Pass");
  console.log("A+");
}

// ! Logical NOT  Operator
let number = 80;

if ((number >= 33 && number <= 80) || !false) {
  console.log("Pass");
}
